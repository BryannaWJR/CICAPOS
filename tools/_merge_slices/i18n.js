function localizeRoot(root) {
  if (!root || !UI.lang || UI.lang === 'EN' || !root.querySelectorAll) return;
  const skip = { SCRIPT: 1, STYLE: 1 };
  const nodes = root.querySelectorAll('*');
  for (let i = 0; i < nodes.length; i++) {
    const el = nodes[i];
    if (skip[el.tagName] || (el.closest && el.closest('[data-keep-en]'))) continue;
    ['placeholder', 'title', 'aria-label'].forEach(a => {
      if (!el.hasAttribute(a)) return;
      const v = el.getAttribute(a), n = locText(v);
      if (n !== v) el.setAttribute(a, n);
    });
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode(node) {
    const p = node.parentElement;
    if (!p || skip[p.tagName] || (p.closest && p.closest('[data-keep-en]'))) return NodeFilter.FILTER_REJECT;
    return NodeFilter.FILTER_ACCEPT;
  }});
  const texts = [];
  while (walker.nextNode()) texts.push(walker.currentNode);
  texts.forEach(n => { const v = n.nodeValue, t = locText(v); if (t !== v) n.nodeValue = t; });
}
function locIssues(issues) {
  return (issues || []).map(function (i) {
    if (!i || i.message == null) return i;
    var msg = i.message;
    if (UI.lang && UI.lang !== 'EN' && (i.code === 'weak_content' || /does not cover|未涵蓋|未涵盖/i.test(msg))
        && /does not cover|missing|未涵蓋|未涵盖|不齊|不齐|缺/i.test(msg)) {
      var parts = [];
      if (/效益|benefit/i.test(msg)) parts.push('預期效益');
      if (/实施|實施|implement|approach/i.test(msg)) parts.push('具成本效益的實施方案');
      if (/目标|目標|objective/i.test(msg) && parts.indexOf('預期效益') < 0) parts.unshift('項目目標');
      msg = parts.length ? ('正文未涵蓋：' + parts.join('、')) : msg;
    }
    return Object.assign({}, i, { message: locText(msg) });
  });
}
